def _write_result(root, direction, mapping, outstanding, bandwidth=None,
                   latency=None, vc=2, depth=8, seed=1, category="baseline",
                   r_rob_depth=128, max_txns_per_id=32, burst_beats=64,
                   transactions_per_flow=1, multicast_mode=None,
                   completion_cycles=1000):
    pattern = mapping.split("_", 1)[0]
    if mapping in ("alltoall", "neighbor_exchange", "pipeline", "many_to_many"):
        pattern = mapping
    mode_tag = f"_{multicast_mode}" if multicast_mode else ""
    burst_tag = f"_bl{burst_beats}" if category == "burst" else ""
    run = root / category / f"{mapping}_{direction}_o{outstanding}_s{seed}_v{vc}_b{depth}{mode_tag}"
    run = run.with_name(run.name + burst_tag)
    run.mkdir(parents=True, exist_ok=True)
    bandwidth = bandwidth if bandwidth is not None else 100.0 * min(outstanding, 4)
    latency = latency if latency is not None else 40.0 + outstanding
    producers, consumers, requests, deliveries, initiators = _TRAFFIC_COUNTS[mapping]
    requests *= transactions_per_flow
    deliveries *= transactions_per_flow
    multicast_mode = (multicast_mode or
                      ("hardware" if mapping.startswith("broadcast_") else ""))
    if multicast_mode == "repeated_unicast":
        requests = deliveries
    row = {
        "topology": "mesh_4x4", "vc": str(vc),
        "router_vc_depth": str(depth), "ni_dat_rx_vc_depth": str(depth),
        "pattern": pattern, "traffic_mapping": mapping,
        "measurement_mode": "outstanding", "direction": direction,
        "data_producers": str(producers), "consumers": str(consumers),
        "axi_initiators": str(initiators), "source_requests": str(requests),
        "payload_deliveries": str(deliveries), "rounds": "16",
        "multicast_mode": multicast_mode,
        "destinations_per_source": str(_BROADCAST_FANOUT.get(mapping, "")),
        "transactions_per_flow": str(transactions_per_flow),
        "bytes_per_flow_round": str(burst_beats * transactions_per_flow * 64),
        "source_outstanding_depth": str(outstanding),
        "source_outstanding_hwm": str(outstanding), "seed": str(seed),
        "max_unique_ids": "8", "max_outstanding": "32",
        "r_rob_depth": str(r_rob_depth),
        "max_txns_per_id": str(max_txns_per_id), "ids_per_initiator": "1",
        "burst_length": str(burst_beats - 1), "burst_beats": str(burst_beats),
        "bytes_per_beat": "64", "transaction_bytes": str(burst_beats * 64),
        "completion_cycles": str(completion_cycles),
        "completion_latency_cycles": str(latency),
        "delivered_payload_bytes_per_cycle": str(bandwidth),
        "checker_status": "PASS", "busiest_dat_link_utilization_pct": "80.0",
        "dat_links_total": "48", "dat_links_ge_25_pct": "12",
        "dat_links_ge_50_pct": "8", "dat_links_ge_75_pct": "4",
        "dat_links_ge_90_pct": "0",
        "nmu_read_slot_hwm_beats": str(min(r_rob_depth, outstanding * 64)),
        "nmu_order_list_hwm_transactions": str(min(max_txns_per_id, outstanding)),
    }
    with (run / "result.csv").open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(row))
        writer.writeheader()
        writer.writerow(row)
    mode = multicast_mode or None
    resources = pr.pm.ai_resource_flits(
        mapping, direction, burst_beats, 16 * transactions_per_flow, mode)
    links = [{"name": name, "flit_count": count, "stall_cyc": 0}
             for name, count in resources.items()]
    (run / "perf.json").write_text(json.dumps({"noc": {"links": links}}))
    return run / "result.csv"


def _complete_baseline(root):
    for direction, mappings in (("write", pr.WRITE_MAPPINGS),
                                ("read", pr.READ_MAPPINGS)):
        for mapping in mappings:
            _write_result(root, direction, mapping, 32)


def _complete_tradeoff_config(root, vc, depth, bandwidth_scale=1.0,
                              latency_scale=1.0):
    stress_rows = (
        ("write", "broadcast_global"),
        ("write", "gather_global_root0"),
        ("read", "gather_global_root0"),
        ("write", "many_to_many"),
        ("read", "many_to_many"),
    )
    for direction, mapping in stress_rows:
        outstanding = 32
        _write_result(
            root, direction, mapping, outstanding,
            bandwidth=400.0 * bandwidth_scale,
            latency=72.0 * latency_scale,
            vc=vc, depth=depth, category=f"tradeoff/v{vc}_b{depth}",
        )


def _complete_channel_compare(root):
    for mapping, architecture in (("2-channel", "rr"), ("3-channel", "rrd")):
        for case, latency in (("write", 4000 if architecture == "rr" else 1000),
                              ("read", 3600 if architecture == "rr" else 3300)):
            run = root / "rr_vs_rrd" / f"{architecture}_{case}"
            run.mkdir(parents=True)
            row = {
                "channel_mapping": mapping, "channel_case": case,
                "control_mean_latency_cycles": str(latency), "seed": "1",
                "data_bursts_per_flow": "32", "data_beats_per_flow": "8192",
                "shared_directed_edge": "1to2", "control_resource": "req_1to2",
                "background_resource": (
                    "dat_1to2" if architecture == "rrd" else
                    "req_1to2"),
                "overlap_status": "PASS",
            }
            with (run / "result.csv").open("w", newline="") as stream:
                writer = csv.DictWriter(stream, fieldnames=list(row))
                writer.writeheader()
                writer.writerow(row)


