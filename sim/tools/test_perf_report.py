def test_burst_rows_require_fixed_payload_and_fixed_outstanding(tmp_path):
    for burst_beats in (1, 4, 16, 64):
        _write_result(
            tmp_path, "write", "pipeline", 32, category="burst",
            burst_beats=burst_beats, transactions_per_flow=64 // burst_beats)

    rows = pr.collect_burst_rows(tmp_path / "burst")
    assert [(row["burst_beats"], row["transactions_per_flow"])
            for row in rows] == [(1, 64), (4, 16), (16, 4), (64, 1)]
    assert all(row["bytes_per_flow_round"] == 4096 for row in rows)

    for mapping in pr.BURST_MAPPINGS:
        for direction in (("write",) if mapping.startswith("broadcast_")
                          else ("write", "read")):
            if (mapping, direction) == ("pipeline", "write"):
                continue
            for burst_beats in (1, 4, 16, 64):
                _write_result(
                    tmp_path, direction, mapping, 32, category="burst",
                    burst_beats=burst_beats,
                    transactions_per_flow=64 // burst_beats)
    table = pr._burst_table(pr.collect_burst_rows(tmp_path / "burst"))
    assert "Accepted Throughput (B/cycle)" in table
    assert "Delivered throughput" not in table

    path = next((tmp_path / "burst").rglob("result.csv"))
    row = next(csv.DictReader(path.open()))
    row["bytes_per_flow_round"] = "4032"
    with path.open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(row))
        writer.writeheader()
        writer.writerow(row)
    with pytest.raises(SystemExit, match="4096 B/flow/round"):
        pr.collect_burst_rows(tmp_path / "burst")


def test_multicast_comparison_pairs_hardware_and_repeated_unicast(tmp_path):
    results = []
    for mapping in pr.WRITE_MAPPINGS[:4]:
        for mode in ("hardware", "repeated_unicast"):
            path = _write_result(
                tmp_path, "write", mapping, 32,
                category="multicast_compare", multicast_mode=mode)
            results.append((path, 1500 if mode == "repeated_unicast" else 600))
    for path, completion in results:
        row = next(csv.DictReader(path.open()))
        row["completion_cycles"] = str(completion)
        with path.open("w", newline="") as stream:
            writer = csv.DictWriter(stream, fieldnames=list(row))
            writer.writeheader()
            writer.writerow(row)

    rows = pr.collect_multicast_rows(tmp_path / "multicast_compare")
    assert {row["multicast_mode"] for row in rows} == {
        "hardware", "repeated_unicast"}
    assert {(row["mapping"], row["destination_count"])
            for row in rows} == {
                ("broadcast_row", 4), ("broadcast_col", 4),
                ("broadcast_submesh", 4), ("broadcast_global", 16),
            }
    assert next(row for row in rows if row["multicast_mode"] == "hardware")[
        "source_requests"] < 256
    assert next(row for row in rows if row["multicast_mode"] == "repeated_unicast")[
        "source_requests"] == 256

    text = pr._multicast_table(rows)
    assert "Destination Set" in text
    assert "Fanout" in text
    assert "Multicast Injected Flits" in text
    assert "Repeated Unicast Injected Flits" in text
    assert "Completion Time" in text
    assert "Multicast scope" not in text
    assert "Destination count" not in text
    assert "| Global Multicast | 16 | 1040 | 600 | 15600 | 1500 | 2.50 |" in text
    assert "source requests" not in text.lower()
    assert "throughput" not in text.lower()


